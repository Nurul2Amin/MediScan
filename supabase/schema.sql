-- Sync stock_qty from batches
create or replace function public.sync_pharmacy_stock_qty()
returns trigger
language plpgsql
as $$
declare
  pm_id bigint;
begin
  pm_id := coalesce(new.pharmacy_medicine_id, old.pharmacy_medicine_id);

  update public.pharmacy_medicines pm
  set stock_qty = (
    select coalesce(sum(b.qty_remaining), 0)
    from public.pharmacy_medicine_batches b
    where b.pharmacy_medicine_id = pm_id
  )
  where pm.id = pm_id;

  return null;
end;
$$;

