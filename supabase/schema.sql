-- Find best pharmacies near user
create or replace function public.find_best_pharmacies(
  user_lat double precision,
  user_lng double precision,
  medicine_ids bigint[],
  radius_m integer default 5000
)
returns table (
  pharmacy_id bigint,
  name text,
  address text,
  latitude double precision,
  longitude double precision,
  matched_items integer,
  total_price numeric,
  distance_m double precision
)
language sql
stable
as $$
  select
    p.pharmacy_id,
    p.name,
    p.address,
    p.latitude,
    p.longitude,
    count(distinct pm.medicine_id)::int as matched_items,
    sum(coalesce(pm.price, m.price)) as total_price,
    st_distance(p.location, st_point(user_lng, user_lat)::geography) as distance_m
  from public.pharmacies p
  join public.pharmacy_medicines pm on pm.pharmacy_id = p.pharmacy_id
  join public.medicines m on m.medicine_id = pm.medicine_id
  where pm.medicine_id = any(medicine_ids)
    and pm.is_available = true
    and pm.stock_qty > 0
    and p.location is not null
    and st_dwithin(p.location, st_point(user_lng, user_lat)::geography, radius_m)
  group by p.pharmacy_id, p.name, p.address, p.latitude, p.longitude, p.location
  order by matched_items desc, total_price asc, distance_m asc;
$$;

-- Stock In (creates/merges batches + writes ledger)
CREATE OR REPLACE FUNCTION public.inventory_stock_in(
  p_pharmacy_medicine_id bigint,
  p_qty_base_units integer,
  p_expiry_date date,
  p_batch_no text default null,
  p_buy_price numeric default null,
  p_note text default null
)
returns bigint
language plpgsql
as $$
declare
  v_batch_id bigint;
  v_pharmacy_id bigint;
  v_entry_id bigint;
begin
  if p_qty_base_units is null or p_qty_base_units <= 0 then
    raise exception 'qty_base_units must be > 0';
  end if;
  if p_expiry_date is null then
    raise exception 'expiry_date is required';
  end if;
  select pm.pharmacy_id into v_pharmacy_id
  from public.pharmacy_medicines pm
  join public.pharmacies p on p.pharmacy_id = pm.pharmacy_id
  where pm.id = p_pharmacy_medicine_id
    and p.owner_id = auth.uid();
  if v_pharmacy_id is null then
    raise exception 'not allowed';
  end if;
  -- merge if batch_no + expiry matches
  if p_batch_no is not null and length(trim(p_batch_no)) > 0 then
    select b.batch_id
      into v_batch_id
    from public.pharmacy_medicine_batches b
    where b.pharmacy_medicine_id = p_pharmacy_medicine_id
      and b.batch_no = p_batch_no
      and b.expiry_date = p_expiry_date
    limit 1;
    if v_batch_id is not null then
      update public.pharmacy_medicine_batches
      set qty_remaining = qty_remaining + p_qty_base_units,
          buy_price = coalesce(p_buy_price, buy_price)
      where batch_id = v_batch_id;
    end if;
  end if;
  if v_batch_id is null then
    insert into public.pharmacy_medicine_batches(
      pharmacy_medicine_id, batch_no, expiry_date, buy_price, qty_remaining
    )
    values (
      p_pharmacy_medicine_id,
      nullif(trim(p_batch_no), ''),
      p_expiry_date,
      p_buy_price,
      p_qty_base_units
    )
    returning batch_id into v_batch_id;
  end if;
  insert into public.inventory_ledger(pharmacy_id, pharmacy_medicine_id, entry_type, qty_base_units, note, created_by)
  values (v_pharmacy_id, p_pharmacy_medicine_id, 'stock_in', p_qty_base_units, p_note, auth.uid())
  returning entry_id into v_entry_id;
  insert into public.inventory_ledger_allocations(entry_id, batch_id, qty_base_units)
  values (v_entry_id, v_batch_id, p_qty_base_units);
  return v_batch_id;
end;
$$;

-- Stock Out (FEFO + active batch priority + writes ledger)
CREATE OR REPLACE FUNCTION public.inventory_stock_out(
  p_pharmacy_medicine_id bigint,
  p_qty_base_units integer,
  p_preferred_batch_id bigint default null,
  p_use_active_batch boolean default true,
  p_note text default null
)
returns jsonb
language plpgsql
as $$
declare
  v_remaining integer := p_qty_base_units;
  v_alloc jsonb := '[]'::jsonb;
  v_take integer;
  v_active_batch_id bigint;
  v_pharmacy_id bigint;
  v_entry_id bigint;
  r record;
begin
  if p_qty_base_units is null or p_qty_base_units <= 0 then
    raise exception 'qty_base_units must be > 0';
  end if;
  select pm.pharmacy_id into v_pharmacy_id
  from public.pharmacy_medicines pm
  join public.pharmacies p on p.pharmacy_id = pm.pharmacy_id
  where pm.id = p_pharmacy_medicine_id
    and p.owner_id = auth.uid();
  if v_pharmacy_id is null then
    raise exception 'not allowed';
  end if;
  select active_batch_id into v_active_batch_id
  from public.pharmacy_medicines
  where id = p_pharmacy_medicine_id;
  insert into public.inventory_ledger(pharmacy_id, pharmacy_medicine_id, entry_type, qty_base_units, note, created_by)
  values (v_pharmacy_id, p_pharmacy_medicine_id, 'stock_out', -p_qty_base_units, p_note, auth.uid())
  returning entry_id into v_entry_id;
  for r in
    select
      b.batch_id,
      b.expiry_date,
      b.qty_remaining
    from public.pharmacy_medicine_batches b
    where b.pharmacy_medicine_id = p_pharmacy_medicine_id
      and b.qty_remaining > 0
      and b.expiry_date >= current_date
    order by
      case when b.batch_id = p_preferred_batch_id then 0 else 1 end,
      case when p_use_active_batch and b.batch_id = v_active_batch_id then 0 else 1 end,
      b.expiry_date asc,
      b.batch_id asc
    for update
  loop
    exit when v_remaining = 0;
    v_take := least(v_remaining, r.qty_remaining);
    update public.pharmacy_medicine_batches
    set qty_remaining = qty_remaining - v_take
    where batch_id = r.batch_id;
    insert into public.inventory_ledger_allocations(entry_id, batch_id, qty_base_units)
    values (v_entry_id, r.batch_id, -v_take);
    v_alloc := v_alloc || jsonb_build_object(
      'batch_id', r.batch_id,
      'take', v_take,
      'expiry_date', r.expiry_date
    );
    v_remaining := v_remaining - v_take;
  end loop;
  if v_remaining > 0 then
    raise exception 'insufficient stock: missing % base units', v_remaining;
  end if;
  return v_alloc;
end;
$$;

-- Move stock between batches (correction tool)
create or replace function public.inventory_move_between_batches(
  p_from_batch_id bigint,
  p_to_batch_id bigint,
  p_qty_base_units integer
)
returns void
language plpgsql
as $$
declare
  v_pm_from bigint;
  v_pm_to bigint;
begin
  if p_qty_base_units is null or p_qty_base_units <= 0 then
    raise exception 'qty_base_units must be > 0';
  end if;

  select pharmacy_medicine_id into v_pm_from
  from public.pharmacy_medicine_batches
  where batch_id = p_from_batch_id
  for update;

  select pharmacy_medicine_id into v_pm_to
  from public.pharmacy_medicine_batches
  where batch_id = p_to_batch_id
  for update;

  if v_pm_from is null or v_pm_to is null then
    raise exception 'batch not found';
  end if;

  if v_pm_from <> v_pm_to then
    raise exception 'batches must belong to same pharmacy_medicine_id';
  end if;

  -- auth check owner
  if not exists (
    select 1
    from public.pharmacy_medicines pm
    join public.pharmacies p on p.pharmacy_id = pm.pharmacy_id
    where pm.id = v_pm_from
      and p.owner_id = auth.uid()
  ) then
    raise exception 'not allowed';
  end if;

  update public.pharmacy_medicine_batches
  set qty_remaining = qty_remaining - p_qty_base_units
  where batch_id = p_from_batch_id
    and qty_remaining >= p_qty_base_units;

  if not found then
    raise exception 'insufficient stock in from-batch';
  end if;

  update public.pharmacy_medicine_batches
  set qty_remaining = qty_remaining + p_qty_base_units
  where batch_id = p_to_batch_id;
end;
$$;

