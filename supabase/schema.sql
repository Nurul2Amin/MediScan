-- Sync default pill conversions from legacy columns
create or replace function public.sync_default_pill_conversions()
returns trigger
language plpgsql
as $$
declare
  v_pills int;
  v_leaflets int;
  v_box_mult int;
begin
  -- Only meaningful for pill-based meds
  if new.unit_type <> 'pill' then
    return new;
  end if;

  v_pills := greatest(coalesce(new.pills_per_leaflet, 1), 1);
  v_leaflets := greatest(coalesce(new.leaflets_per_box, 1), 1);
  v_box_mult := v_pills * v_leaflets;

  -- Ensure base unit exists
  insert into public.pharmacy_unit_conversions(pharmacy_medicine_id, unit_label, multiplier_to_base, is_default)
  values (new.id, 'pill', 1, true)
  on conflict (pharmacy_medicine_id, unit_label, multiplier_to_base) do update
    set is_default = true;

  -- Default leaflet
  insert into public.pharmacy_unit_conversions(pharmacy_medicine_id, unit_label, multiplier_to_base, is_default)
  values (new.id, 'leaflet', v_pills, true)
  on conflict (pharmacy_medicine_id, unit_label, multiplier_to_base) do update
    set is_default = true;

  -- Default box
  insert into public.pharmacy_unit_conversions(pharmacy_medicine_id, unit_label, multiplier_to_base, is_default)
  values (new.id, 'box', v_box_mult, true)
  on conflict (pharmacy_medicine_id, unit_label, multiplier_to_base) do update
    set is_default = true;

  return new;
end;
$$;

drop trigger if exists trg_sync_default_pill_conversions on public.pharmacy_medicines;
create trigger trg_sync_default_pill_conversions
after insert or update of pills_per_leaflet, leaflets_per_box, unit_type
on public.pharmacy_medicines
for each row execute function public.sync_default_pill_conversions();

